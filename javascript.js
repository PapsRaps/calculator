function addCalc(num1, num2){
    return num1 + num2;
}

function subtractCalc(num1, num2){
    return num1 - num2;
}

function multiplyCalc(num1, num2){
    return num1 * num2;
}

function divideCalc(num1, num2){
    return num1/num2;
}

console.log(addCalc(1,2))
console.log(subtractCalc(1,2))
console.log(multiplyCalc(3,2))
console.log(divideCalc(8,2))